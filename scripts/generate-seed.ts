// Generates supabase/seed.sql from the built-in demo catalog.
// Run with:  npx tsx scripts/generate-seed.ts
import { writeFileSync } from 'node:fs'
import { destinationToRow, tripToRow } from '../src/lib/catalog'
import { staticCatalog } from '../src/lib/staticCatalog'

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  return `'${String(v).replace(/'/g, "''")}'`
}
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`
const arr = (v: string[]) => `array[${v.map(q).join(', ')}]::text[]`

const { destinations, trips } = staticCatalog()
const lines: string[] = [
  '-- KM Tours — initial data (generated by scripts/generate-seed.ts)',
  '-- Run after schema.sql. Safe to re-run: existing rows are updated.',
  '',
]

for (const d of destinations.map(destinationToRow)) {
  lines.push(
    `insert into public.destinations (id, name, description, cover_photo, sort_order, published) values (` +
      [q(d.id), json(d.name), json(d.description), q(d.cover_photo), q(d.sort_order), q(d.published)].join(', ') +
      `)\non conflict (id) do update set name = excluded.name, description = excluded.description, cover_photo = excluded.cover_photo, sort_order = excluded.sort_order;`,
  )
}
lines.push('')

for (const t of trips.map(tripToRow)) {
  lines.push(
    `insert into public.experiences (id, destination_id, category, price, child_price, duration_hours, tour_languages, pickup_available, free_cancellation, provider, photos, rating, review_count, reviews, content, max_guests, children_allowed, child_min_age, child_max_age, infants_allowed, published, featured, sort_order) values (` +
      [
        q(t.id),
        q(t.destination_id),
        q(t.category),
        q(t.price),
        q(t.child_price),
        q(t.duration_hours),
        arr(t.tour_languages ?? []),
        q(t.pickup_available),
        q(t.free_cancellation),
        q(t.provider),
        arr(t.photos ?? []),
        q(t.rating),
        q(t.review_count),
        `'[]'::jsonb`,
        json(t.content),
        q(t.max_guests),
        q(t.children_allowed),
        q(t.child_min_age),
        q(t.child_max_age),
        q(t.infants_allowed),
        q(t.published),
        q(t.featured),
        q(t.sort_order),
      ].join(', ') +
      `)\non conflict (id) do nothing;`,
  )
}

lines.push('', '-- Existing guest reviews (shown as approved, already counted in each trip rating)')
for (const t of trips) {
  for (const r of t.reviews) {
    lines.push(
      `insert into public.reviews (experience_id, name, country, rating, comment, date_label, status, source) ` +
        `select ${q(t.id)}, ${q(r.name)}, ${q(r.country)}, ${q(r.rating)}, ${q(r.comment)}, ${q(r.date)}, 'approved', 'imported' ` +
        `where not exists (select 1 from public.reviews where experience_id = ${q(t.id)} and name = ${q(r.name)} and comment = ${q(r.comment)});`,
    )
  }
}

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n') + '\n')
console.log(`seed.sql written: ${destinations.length} destinations, ${trips.length} trips`)
